#!/usr/bin/env node

import { cpSync, existsSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(packageDir, "..", "scaffold");
const destination = join(packageDir, "scaffold");
const marker = join(destination, ".staged-by-prepack");

const command = process.argv[2];
if (command === "prepare") {
  if (!existsSync(join(source, "package.json"))) {
    throw new Error(`canonical scaffold not found: ${source}`);
  }
  rmSync(destination, { recursive: true, force: true });
  cpSync(source, destination, { recursive: true });
  writeFileSync(marker, "generated by npm prepack\n", "utf8");
} else if (command === "cleanup") {
  if (existsSync(marker)) rmSync(destination, { recursive: true, force: true });
} else {
  throw new Error("usage: stage-scaffold.mjs prepare|cleanup");
}
